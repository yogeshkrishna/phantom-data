def build_suite(root: Path, requests, identities, audit_log, activity, manifest, evidence, expected,
                link_policy: str | None = None) -> None:
    if root.exists():
        shutil.rmtree(root)
    data = root / FIXTURE_DIR
    write_csv(data / "deletion_requests.csv",
              ["case_id", "email", "requested_at", "reported_status", "reported_at", "audit_at", "request_text"], requests)
    write_csv(data / "user_identities.csv", ["user_id", "name", "email", "phone", "email_hash", "updated_at"], identities)
    write_csv(data / "user_audit_log.csv", ["audit_id", "user_id", "event_time", "field_name", "old_value", "new_value"],
              audit_log)
    write_csv(data / "system_activity.csv", ["activity_id", "event_time", "event_type", "source_system", "target_system",
                                             "resource_id", "reported_result", "details"], activity)
    write_csv(data / "evidence_files.csv", ["file_id", "file_path", "origin", "captured_at"], manifest)
    shutil.copy(REPO_RULES, data / "deletion_rules.csv")
    for rel, content in evidence.items():
        path = data / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    rows = []
    for case_id, (status, steps) in expected.items():
        objs = [{"step_no": i, "phase": p, "system_id": s, "resource_id": r, "operation": op, "state": st,
                 "evidence_id": ev} for i, (p, s, r, op, st, ev) in enumerate(steps, start=1)]
        rows.append((case_id, status, json.dumps(objs, separators=(",", ":"))))
    write_csv(root / "expected_output.csv", ["case_id", "deletion_status", "steps_json"], rows)
    if link_policy:
        (root / "link_policy.txt").write_text(link_policy + "\n", encoding="utf-8")
    print(f"built {len(requests)} custom cases in {root}")


